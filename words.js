const TOTAL_WORDS = Object.values(LESSON_WORDS).reduce(
  (sum, words) => sum + words.length, 0
);

/* =========================================================
   கடின நிலைக்கேற்ப சொற்களைத் தேர்ந்தெடுக்கும் சார்பு
   =========================================================
   
   @param {number} lessonId - பாட எண் (1-13)
   @param {number} gridSize - கட்ட அளவு (7, 8, 9, 10)
   @returns {string[]} - தேர்ந்தெடுக்கப்பட்ட சொற்களின் வரிசை
   
   எடுத்துக்காட்டு:
   - 7×7 கட்டத்திற்கு → 6 சொற்கள் (எளிது)
   - 8×8 கட்டத்திற்கு → 8 சொற்கள் (நடுத்தரம்)
   - 9×9 கட்டத்திற்கு → 10 சொற்கள் (கடினம்)
   - 10×10 கட்டத்திற்கு → 12 சொற்கள் (மிக கடினம்)
   ========================================================= */
function getWordsForGame(lessonId, gridSize) {
  const allWords = LESSON_WORDS[lessonId] || LESSON_WORDS[1];

  // கட்ட அளவுக்கேற்ப சொற்களின் எண்ணிக்கை
  let wordCount;
  if (gridSize <= 7) wordCount = 6;
  else if (gridSize <= 8) wordCount = 8;
  else if (gridSize <= 9) wordCount = 10;
  else wordCount = 12;

  // கிடைக்கக்கூடிய சொற்களின் எண்ணிக்கையை விட அதிகமாக வேண்டாம்
  wordCount = Math.min(wordCount, allWords.length);

  // சொற்களைக் கலந்து சீரற்ற முறையில் தேர்ந்தெடு
  const shuffled = [...allWords].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, wordCount);
}

/* =========================================================
   பாடத்தின் அனைத்து சொற்களையும் பெறும் சார்பு
   ========================================================= */
function getAllWordsForLesson(lessonId) {
  return [...(LESSON_WORDS[lessonId] || LESSON_WORDS[1])];
}

/* =========================================================
   சொல் பட்டியலைச் சரிபார்க்கும் சார்பு (Debug)
   ========================================================= */
function validateWords() {
  const errors = [];
  Object.keys(LESSON_WORDS).forEach(lessonId => {
    const words = LESSON_WORDS[lessonId];
    if (words.length < 6) {
      errors.push(`பாடம் ${lessonId}: குறைந்தது 6 சொற்கள் தேவை (${words.length} உள்ளன)`);
    }
    words.forEach(word => {
      if (word.length < 2) {
        errors.push(`பாடம் ${lessonId}: "${word}" மிகச் சிறியது`);
      }
      if (word.length > 10) {
        errors.push(`பாடம் ${lessonId}: "${word}" மிக நீளமானது`);
      }
    });
  });

  if (errors.length === 0) {
    console.log('✅ அனைத்து சொற்களும் சரியாக உள்ளன!');
    console.log(`📚 மொத்த பாடங்கள்: ${Object.keys(LESSON_WORDS).length}`);
    console.log(`📝 மொத்த சொற்கள்: ${TOTAL_WORDS}`);
  } else {
    console.warn('⚠️ சொல் சரிபார்ப்பில் பிழைகள்:');
    errors.forEach(e => console.warn('  -', e));
  }
  return errors;
}

